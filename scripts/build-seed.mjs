const sql = `-- Absolute Racing Team app: starting data. Generated by scripts/build-seed.mjs, do not edit by hand.
-- Run after schema.sql. Running it again updates these rows and never deletes anything.

insert into public.championships (id, name, short_name) values
${values(championships)}
on conflict (id) do update set name = excluded.name, short_name = excluded.short_name;

insert into public.cars (id, number, model, championship_id) values
${values(cars)}
on conflict (id) do nothing;

insert into public.channels (id, name, roles, position) values
${values(channels)}
on conflict (id) do nothing;

insert into public.guide_sections (id, position, title, body) values
${values(guide)}
on conflict (id) do nothing;

insert into public.series_sources (id, championship_id, adapter, kind, label, url) values
${values(sources)}
on conflict (id) do nothing;

-- 2027 season calendar (${events.length} events).
insert into public.events (id, name, championship_id, circuit, location, latitude, longitude, start_date, end_date, summary) values
${values(events.map((e) => [e.id, e.name, e.championshipId, e.circuit, e.location, e.latitude, e.longitude, e.startDate, e.endDate, e.summary]))}
on conflict (id) do update set
  name = excluded.name, championship_id = excluded.championship_id, circuit = excluded.circuit,
  location = excluded.location, latitude = excluded.latitude, longitude = excluded.longitude,
  start_date = excluded.start_date, end_date = excluded.end_date, summary = excluded.summary;
`;

writeFileSync('supabase/seed.sql', sql);
