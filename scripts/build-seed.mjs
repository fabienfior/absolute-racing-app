// Writes supabase/seed.sql: championships, placeholder cars, chat channels, team guide headings,
// series pages and the 2027 calendar (src/data/calendar.ts + src/data/calendar-pcca.ts).
// Usage: node scripts/build-seed.mjs
// Safe to run in Supabase more than once: existing rows are updated, nothing is deleted.
import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

async function load(path) {
  const js = ts.transpileModule(readFileSync(path, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  return import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
}

const { calendarEvents } = await load('src/data/calendar.ts');
const { pccaEvents } = await load('src/data/calendar-pcca.ts');
const events = [...calendarEvents, ...pccaEvents].sort((a, b) => a.startDate.localeCompare(b.startDate));

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const values = (rows) => rows.map((r) => `  (${r.map(q).join(', ')})`).join(',\n');

